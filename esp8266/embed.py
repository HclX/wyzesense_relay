# PlatformIO pre-build script: what the relay's firmware carries, as C headers in the build directory.
#   index_html.h     the relays' shared web page (web/index.html), kIndexHtml
#   gateway_image.h  the gateway images for the contact board (#76, gateway_image.py: OWS and stock v1.8):
#                    kGatewayImage, kGatewayImageLen, kStockGatewayImage, kStockGatewayImageLen.
#   relay_version.h  OWS_RELAY_VERSION: git describe, for the status page
# The ESP32-S3 build embeds the same files (idf/main/CMakeLists.txt).
import pathlib
import subprocess
import sys

Import('env')  # noqa: F821 (SCons)

project = pathlib.Path(env.subst('$PROJECT_DIR'))  # noqa: F821
root = project.parent
out = pathlib.Path(env.subst('$BUILD_DIR')) / 'gen'  # noqa: F821
out.mkdir(parents=True, exist_ok=True)


def write(name, text):
    f = out / name
    if not f.exists() or f.read_text() != text:
        f.write_text(text)


def array(data):
    return ',\n'.join(','.join(str(b) for b in data[i : i + 32]) for i in range(0, len(data), 32))


html = (root / 'web' / 'index.html').read_bytes()
write(
    'index_html.h',
    '// generated from web/index.html by embed.py\n#pragma once\n#include <pgmspace.h>\n'
    f'static const char kIndexHtml[] PROGMEM = {{\n{array(html)},0}};\n',
)

subprocess.run([sys.executable, str(root / 'gateway_image.py'), str(out / 'gateway.bin')], check=True)
subprocess.run(
    [sys.executable, str(root / 'gateway_image.py'), '--stock', str(out / 'gateway_stock.bin')],
    check=True,
)
gw = (out / 'gateway.bin').read_bytes()
gw_stock = (out / 'gateway_stock.bin').read_bytes()
write(
    'gateway_image.h',
    '// generated by embed.py (gateway_image.py)\n#pragma once\n#include <pgmspace.h>\n'
    f'static const uint8_t kGatewayImage[] PROGMEM __attribute__((aligned(4))) = {{\n{array(gw)}}};\n'
    f'static const uint32_t kGatewayImageLen = {len(gw)};\n'
    f'static const uint8_t kStockGatewayImage[] PROGMEM __attribute__((aligned(4))) = {{\n{array(gw_stock)}}};\n'
    f'static const uint32_t kStockGatewayImageLen = {len(gw_stock)};\n',
)

version = subprocess.run(
    ['git', 'describe', '--always', '--dirty', '--tags'], cwd=root, capture_output=True, text=True
).stdout.strip()
write('relay_version.h', f'#pragma once\n#define OWS_RELAY_VERSION "{version or "unknown"}"\n')
env.Append(CPPPATH=[str(out)])  # noqa: F821
